-- Headcount Desk schema. Plain Postgres, no ORM.
-- Applied by scripts/migrate.py. Views live in views.sql and checks.sql.

-- The business day, defined once. It runs on US Eastern time and starts at
-- 6 AM, when the morning snapshot loads. So "90 days old" and "overnight" do
-- not flip at 7 PM because the server is on UTC, and at 2 AM the data is
-- still "as of yesterday morning" rather than a time that has not happened.
CREATE FUNCTION today() RETURNS date
LANGUAGE sql STABLE AS $$ SELECT ((now() AT TIME ZONE 'America/New_York') - interval '6 hours')::date $$;


-- ── Org chart ───────────────────────────────────────────────────────────────

CREATE TABLE orgs (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              text NOT NULL,
    parent_id         integer REFERENCES orgs (id),
    level             text NOT NULL CHECK (level IN ('company', 'svp', 'vp', 'director', 'team')),
    leader_person_id  integer,                       -- FK added below, once people exists
    cost_center       text NOT NULL UNIQUE,
    created_at        timestamptz NOT NULL DEFAULT now(),
    -- only the company has no parent
    CHECK ((level = 'company') = (parent_id IS NULL))
);

CREATE TABLE people (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   text NOT NULL,
    email       text NOT NULL UNIQUE,
    org_id      integer NOT NULL REFERENCES orgs (id),
    job_family  text NOT NULL CHECK (job_family IN ('research', 'eng', 'ops', 'g&a')),
    level       text NOT NULL CHECK (level ~ '^L[3-9]$'),
    location    text NOT NULL,
    start_date  date NOT NULL,
    end_date    date,                                -- null = active; future = notice given
    manager_id  integer REFERENCES people (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date IS NULL OR end_date >= start_date)
);

-- orgs and people point at each other, so this one is checked at commit time.
ALTER TABLE orgs
    ADD CONSTRAINT orgs_leader_fk FOREIGN KEY (leader_person_id) REFERENCES people (id)
    DEFERRABLE INITIALLY DEFERRED;


-- ── Positions and recruiting ────────────────────────────────────────────────

-- A position is a seat. Whether it is "open" is NOT stored: it is derived in
-- v_position_status from person_id and staffing_requests.
CREATE TABLE positions (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_code  text NOT NULL UNIQUE,
    org_id         integer NOT NULL REFERENCES orgs (id),
    job_family     text NOT NULL CHECK (job_family IN ('research', 'eng', 'ops', 'g&a')),
    level          text NOT NULL CHECK (level ~ '^L[3-9]$'),
    position_type  text NOT NULL DEFAULT 'standard'
                   CHECK (position_type IN ('standard', 'reserve', 'negative')),
    person_id      integer REFERENCES people (id),   -- null = nobody in the seat
    opened_at      date NOT NULL,                    -- when the seat was created or last vacated
    source         text NOT NULL DEFAULT 'plan' CHECK (source IN ('plan', 'backfill', 'transfer')),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX positions_org_idx ON positions (org_id);
CREATE INDEX positions_person_idx ON positions (person_id);

CREATE TABLE recruiter_coverage (
    person_id   integer PRIMARY KEY REFERENCES people (id),
    job_family  text NOT NULL CHECK (job_family IN ('research', 'eng', 'ops', 'g&a')),
    created_at  timestamptz NOT NULL DEFAULT now()
);


-- ── The plan: versioned, then locked ────────────────────────────────────────

CREATE TABLE plan_versions (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL UNIQUE,
    locked_at     timestamptz,                       -- null = still a draft
    locked_by     integer REFERENCES people (id),
    content_hash  text,                              -- sha256 of the lines at lock time
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE plan_lines (
    plan_version_id     integer NOT NULL REFERENCES plan_versions (id),
    org_id              integer NOT NULL REFERENCES orgs (id),
    job_family          text NOT NULL CHECK (job_family IN ('research', 'eng', 'ops', 'g&a')),
    approved_headcount  integer NOT NULL CHECK (approved_headcount >= 0),
    approved_cost_usd   numeric(14, 2) NOT NULL CHECK (approved_cost_usd >= 0),
    created_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (plan_version_id, org_id, job_family)
);

-- A fingerprint of a plan's lines. Stored at lock time, recomputed by a daily check.
CREATE FUNCTION plan_hash(version_id integer) RETURNS text
LANGUAGE sql STABLE AS $$
    SELECT encode(sha256(convert_to(coalesce(string_agg(
               org_id || '|' || job_family || '|' || approved_headcount || '|' || approved_cost_usd,
               E'\n' ORDER BY org_id, job_family), ''), 'UTF8')), 'hex')
    FROM plan_lines
    WHERE plan_version_id = version_id
$$;

-- Prevention: once a plan is locked, its lines cannot be added, changed or removed.
CREATE FUNCTION block_locked_plan_edits() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_id integer := CASE WHEN TG_OP = 'DELETE' THEN OLD.plan_version_id ELSE NEW.plan_version_id END;
BEGIN
    IF EXISTS (SELECT 1 FROM plan_versions WHERE id = v_id AND locked_at IS NOT NULL) THEN
        RAISE EXCEPTION 'plan version % is locked; create a new version instead', v_id;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER plan_lines_locked
    BEFORE INSERT OR UPDATE OR DELETE ON plan_lines
    FOR EACH ROW EXECUTE FUNCTION block_locked_plan_edits();


-- ── Backfill workflow ───────────────────────────────────────────────────────

CREATE TABLE backfill_requests (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departing_person_id  integer NOT NULL REFERENCES people (id),
    position_id          integer NOT NULL REFERENCES positions (id),
    requested_by         integer NOT NULL REFERENCES people (id),
    justification        text NOT NULL,
    urgency              text NOT NULL DEFAULT 'normal' CHECK (urgency IN ('low', 'normal', 'urgent')),
    status               text NOT NULL DEFAULT 'submitted'
                         CHECK (status IN ('submitted', 'vp_approved', 'rejected',
                                           'recruiter_assigned', 'req_open', 'filled')),
    vp_approver_id       integer REFERENCES people (id),   -- who must approve (the VP over the seat)
    recruiter_id         integer REFERENCES people (id),   -- set on auto-assignment
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()  -- when it entered its current status
);
-- one live backfill per seat
CREATE UNIQUE INDEX backfill_one_active_per_position
    ON backfill_requests (position_id) WHERE status NOT IN ('rejected', 'filled');

CREATE TABLE staffing_requests (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id          integer NOT NULL REFERENCES positions (id),
    recruiter_id         integer REFERENCES people (id),
    status               text NOT NULL DEFAULT 'open'
                         CHECK (status IN ('open', 'offer_out', 'filled', 'cancelled')),
    backfill_request_id  integer REFERENCES backfill_requests (id),  -- set when the workflow created it
    opened_at            date NOT NULL,
    closed_at            date,
    created_at           timestamptz NOT NULL DEFAULT now()
);
-- one active request per seat, so a seat can never be counted as committed twice
CREATE UNIQUE INDEX staffing_one_active_per_position
    ON staffing_requests (position_id) WHERE status IN ('open', 'offer_out');
CREATE INDEX staffing_recruiter_idx ON staffing_requests (recruiter_id);

-- Audit trail. One row per status change, written by app/workflow.py: transition().
CREATE TABLE request_events (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backfill_request_id  integer NOT NULL REFERENCES backfill_requests (id),
    from_status          text,                        -- null on the first event
    to_status            text NOT NULL,
    actor_id             integer REFERENCES people (id),  -- null = the system
    note                 text,
    at                   timestamptz NOT NULL DEFAULT now(),
    created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX request_events_request_idx ON request_events (backfill_request_id, at);

CREATE FUNCTION block_event_edits() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'request_events is append-only';
END $$;

CREATE TRIGGER request_events_append_only
    BEFORE UPDATE OR DELETE ON request_events
    FOR EACH ROW EXECUTE FUNCTION block_event_edits();


-- ── Exceptions ──────────────────────────────────────────────────────────────

-- The exceptions themselves are derived (v_exceptions). This only records that
-- someone has dealt with one.
CREATE TABLE exception_resolutions (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exception_type  text NOT NULL,
    position_id     integer NOT NULL REFERENCES positions (id),
    resolved_by     integer REFERENCES people (id),
    resolved_at     timestamptz NOT NULL DEFAULT now(),
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (exception_type, position_id)
);


-- ── Snapshots and data checks ───────────────────────────────────────────────

-- Rolled-up totals for every org, every day. Stored so today can be tied out
-- against yesterday.
CREATE TABLE daily_snapshots (
    snapshot_date  date NOT NULL,
    org_id         integer NOT NULL REFERENCES orgs (id),
    filled         integer NOT NULL,
    open_with_req  integer NOT NULL,
    open_no_req    integer NOT NULL,
    reserve        integer NOT NULL,
    negative       integer NOT NULL,
    total_people   integer NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (snapshot_date, org_id)
);

CREATE TABLE check_runs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_at      timestamptz NOT NULL DEFAULT now(),
    passed      integer NOT NULL DEFAULT 0,          -- number of checks, not rows
    warned      integer NOT NULL DEFAULT 0,
    failed      integer NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE check_results (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_run_id  integer NOT NULL REFERENCES check_runs (id) ON DELETE CASCADE,
    check_name    text NOT NULL,
    org_id        integer REFERENCES orgs (id),
    severity      text NOT NULL CHECK (severity IN ('pass', 'warn', 'fail')),
    expected      numeric,
    actual        numeric,
    message       text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX check_results_run_idx ON check_results (check_run_id);


-- ── App bookkeeping ─────────────────────────────────────────────────────────

-- Small key/value store: the date the demo data was built for, who the demo
