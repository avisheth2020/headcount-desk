-- 003: annual planning. Each VP proposes changes to next year's headcount, the
-- SVP reviews them against an envelope, and locking the cycle writes a new
-- plan_version. Every status change is logged, like backfills.

CREATE TABLE planning_cycles (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    text NOT NULL UNIQUE,                         -- 'FY28 Planning'
    fiscal_year             text NOT NULL REFERENCES fiscal_years (name), -- the year being planned
    base_plan_version_id    integer NOT NULL REFERENCES plan_versions (id),  -- where every VP starts from
    status                  text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'locked')),
    locked_plan_version_id  integer REFERENCES plan_versions (id),        -- the plan this cycle produced
    locked_at               timestamptz,
    locked_by               integer REFERENCES people (id),
    created_at              timestamptz NOT NULL DEFAULT now()
);

-- The top-down limit each SVP has to fit their VPs' asks into.
CREATE TABLE planning_envelopes (
    cycle_id            integer NOT NULL REFERENCES planning_cycles (id),
    svp_org_id          integer NOT NULL REFERENCES orgs (id),
    headcount_envelope  integer NOT NULL CHECK (headcount_envelope >= 0),
    cost_envelope_usd   numeric(14, 2) NOT NULL CHECK (cost_envelope_usd >= 0),
    created_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (cycle_id, svp_org_id)
);

-- One submission per VP org per cycle.
CREATE TABLE plan_submissions (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id    integer NOT NULL REFERENCES planning_cycles (id),
    vp_org_id   integer NOT NULL REFERENCES orgs (id),
    status      text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'sent_back', 'approved')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (cycle_id, vp_org_id)
);

-- A VP's ask, by job family: this year's number, the change they want, and why.
-- The SVP may approve a different change; NULL means "as requested".
CREATE TABLE plan_submission_lines (
    submission_id     integer NOT NULL REFERENCES plan_submissions (id),
    job_family        text NOT NULL CHECK (job_family IN ('research', 'eng', 'ops', 'g&a')),
    base_headcount    integer NOT NULL CHECK (base_headcount >= 0),
    base_cost_usd     numeric(14, 2) NOT NULL CHECK (base_cost_usd >= 0),
    requested_change  integer NOT NULL DEFAULT 0 CHECK (requested_change BETWEEN -500 AND 500),
    approved_change   integer CHECK (approved_change BETWEEN -500 AND 500),
    justification     text NOT NULL DEFAULT '',
    created_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (submission_id, job_family),
    CHECK (base_headcount + requested_change >= 0)
);

-- Audit trail for the cycle. submission_id is NULL for cycle-level events (the lock).
CREATE TABLE planning_events (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id       integer NOT NULL REFERENCES planning_cycles (id),
    submission_id  integer REFERENCES plan_submissions (id),
    from_status    text,
    to_status      text NOT NULL,
    actor_id       integer REFERENCES people (id),
    note           text,
    at             timestamptz NOT NULL DEFAULT now(),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX planning_events_submission_idx ON planning_events (submission_id, at);

CREATE TRIGGER planning_events_append_only
    BEFORE UPDATE OR DELETE ON planning_events
    FOR EACH ROW EXECUTE FUNCTION block_event_edits();
